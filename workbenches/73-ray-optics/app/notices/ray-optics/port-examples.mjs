#!/usr/bin/env node
// Ports a curated set of upstream gallery scenes (Apache-2.0, ricktu288/ray-optics
// data/galleryScenes at the pinned commit) into app/src/contracts/examples-data.ts.
//
//   node app/notices/ray-optics/port-examples.mjs /path/to/ray-optics
//
// Adaptations (recorded per example): {{placeholder}} text labels are resolved
// from the upstream zh-CN gallery locale (English fallback); CropBox objects
// (used upstream only to frame gallery thumbnails) and the importedFromBeta flag
// are removed; the scene name is set to the Chinese title. Optics are untouched.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '../..');
const upstream = resolve(process.argv[2] ?? '.');
const picks = [
  ['chromatic-dispersion', '棱镜色散', '色散', '白光经三棱镜按波长分开，拖动标记点可旋转棱镜或改变光束宽度。'],
  ['prisms', '反射棱镜', '反射', '直角、波罗、菱形、杜福和五面棱镜借全反射改变光路方向。'],
  ['spherical-lens-and-mirror', '球面透镜与凹面镜', '成像', '同一束平行光经厚球面透镜和圆弧凹面镜会聚，可比较两者的焦点。'],
  ['parabolic-mirror', '抛物面镜聚焦', '反射', '平行光经抛物面镜会聚于焦点，点光源放在焦点则反射为平行光。'],
  ['orientations-of-plano-convex-lens', '平凸厚透镜的朝向', '透镜', '同一平凸透镜正放与反放时球差不同，适合比较厚透镜像差。'],
  ['convex-lens', '凸透镜（厚透镜）', '透镜', '以曲率半径和厚度定义的球面凸透镜，会聚平行光。'],
  ['concave-lens', '凹透镜（延长线）', '透镜', '凹透镜发散平行光，延长线模式显示虚焦点。'],
  ['keplerian-telescope', '开普勒望远镜', '仪器', '物镜成实像、目镜放大为虚像，延长线模式显示像的位置。'],
  ['newtonian-telescope', '牛顿望远镜', '仪器', '抛物面主镜会聚星光，平面副镜把焦点引出镜筒。'],
  ['internal-reflection', '全内反射', '折射', '点光源在玻璃内射向界面，超过临界角的光线全部反射。'],
  ['types-of-spectrometer-dispersive-elements', '棱镜与光栅分光', '色散', '棱镜、透射/反射光栅与棱栅对同一复色光的分光比较。'],
  ['reflecting-monochromator', '反射式单色仪', '色散', '凹面镜准直、光栅分光，旋转光栅在出射狭缝选出窄带单色光。'],
  ['apparent-depth', '水中视深（观察者）', '成像', '观察者模式：从水面上方看水中物体，观察到的像比实际更浅。'],
  ['transverse-and-longitudinal-magnification', '横向与纵向放大率', '成像', '成像模式：理想透镜对一串点光源成像，比较横向与纵向放大率。'],
  ['inferior-mirage', '下蜃景（渐变折射率）', '折射', '近地面空气折射率渐变，使光线向上弯曲，形成倒立的蜃景。'],
  ['rainbows', '彩虹', '色散', '阳光在雨滴内一次/两次反射形成虹与霓，以及其间的亚历山大暗带。'],
];
const list = JSON.parse(readFileSync(join(upstream, 'data/galleryList.json'), 'utf8'));
const contributors = Object.fromEntries(list.flatMap((g) => g.content.map((c) => [c.id, c.contributors])));
const zh = JSON.parse(readFileSync(join(upstream, 'locales/zh-CN/gallery.json'), 'utf8')).galleryData;
const en = JSON.parse(readFileSync(join(upstream, 'locales/en/gallery.json'), 'utf8')).galleryData;
const camel = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
// Upstream zh-CN gallery strings mix a few traditional characters.
const simplify = (s) => s.replace(/稜/g, '棱').replace(/鏡/g, '镜').replace(/座标/g, '坐标');
const out = [];
for (const [id, title, topic, summary] of picks) {
  const path = 'data/galleryScenes/' + id + '.json';
  const raw = readFileSync(join(upstream, path));
  const scene = JSON.parse(raw);
  const key = camel(id);
  const text = (k) => simplify(zh[key]?.[k] ?? zh.common?.[k] ?? en[key]?.[k] ?? en.common?.[k] ?? '');
  scene.objs = scene.objs
    .filter((o) => o.type !== 'CropBox')
    .map((o) => (typeof o.text === 'string' ? { ...o, text: o.text.replace(/\{\{(\w+)\}\}/g, (_, k) => text(k)) } : o))
    .filter((o) => o.type !== 'TextLabel' || o.text.trim());
  delete scene.importedFromBeta;
  scene.name = title;
  if (!contributors[id]) throw new Error('No contributors for ' + id);
  out.push({
    id,
    title,
    topic,
    summary,
    contributors: contributors[id],
    upstreamPath: path,
    upstreamSha256: createHash('sha256').update(raw).digest('hex'),
    scene: JSON.stringify(scene),
  });
}
writeFileSync(
  join(app, 'src/contracts/examples-data.ts'),
  '// Generated by app/notices/ray-optics/port-examples.mjs from Ray Optics Simulation\n' +
    '// gallery scenes (Apache-2.0, https://github.com/ricktu288/ray-optics, commit\n' +
    '// daf76772c73a85e1a2568c4e2e71613bba1fab77). Text placeholders resolved from the\n' +
    '// upstream zh-CN gallery locale; CropBox thumbnail frames removed. Do not edit by hand.\n' +
    'export interface PortedExample {\n  id: string;\n  title: string;\n  topic: string;\n  summary: string;\n  contributors: string[];\n  upstreamPath: string;\n  upstreamSha256: string;\n  scene: string;\n}\n' +
    'export const portedExamples: PortedExample[] = [\n' +
    out.map((e) => '  ' + JSON.stringify(e)).join(',\n') +
    '\n];\n',
);
console.log('ported', out.length, 'examples');
