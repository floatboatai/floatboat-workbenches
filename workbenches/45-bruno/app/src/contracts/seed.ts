// Seed and blank collections: realistic demonstration content that works on first open.
import type { Collection } from "./bruno.ts";

const lines = (...xs: string[]) => xs.join("\n") + "\n";

export const blankRequestSource = lines(
  "meta {",
  "  name: 新请求",
  "  type: http",
  "  seq: 1",
  "}",
  "",
  "get {",
  "  url: {{baseUrl}}/health",
  "  body: none",
  "  auth: none",
  "}",
);

const collectionConfig = (name: string) =>
  JSON.stringify(
    { version: "1", name, type: "collection", ignore: ["node_modules", ".git"] },
    null,
    2,
  ) + "\n";

export function blankCollection(name = "新集合"): Collection {
  return {
    files: [
      { id: crypto.randomUUID(), path: "bruno.json", source: collectionConfig(name) },
      {
        id: crypto.randomUUID(),
        path: "environments/本机回声.bru",
        source: lines("vars {", "  baseUrl: {{$localEcho}}", "}"),
      },
      { id: crypto.randomUUID(), path: "请求.bru", source: blankRequestSource },
    ],
    results: [],
    notes: "",
    activeEnvironment: "本机回声",
  };
}

