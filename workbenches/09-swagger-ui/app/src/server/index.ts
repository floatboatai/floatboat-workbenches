import { registerAutosaveRoutes } from "./autosave";
import { createWorkbenchServer } from "../../sdk/runtime.mjs";
import { registerRoutes } from "./routes";
import { validate, instructions, fromGenerated } from "../contracts/model";
import { registerSwaggerView } from "./swagger-view";
import { registerSampleApi } from "./sample-api";
import { registerAppRoute } from "./app-route";
const app = await createWorkbenchServer(import.meta.url);
registerAppRoute(app);
registerRoutes(app, validate, instructions, fromGenerated);
registerSwaggerView(app);
registerSampleApi(app);
registerAutosaveRoutes(app, validate);
await app.listen();
